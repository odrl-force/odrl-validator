import * as path from "path"
import * as fs from "fs"
import { write } from "@jeswr/pretty-turtle"
import { Quad } from "@rdfjs/types";
import { getConfigSync } from "./Util";
import { rdfDereferencer } from "rdf-dereference";
import { arrayifyStream } from "arrayify-stream";
import { DataFactory, Store } from "n3";
const { namedNode } = DataFactory

const profileDir = path.join(path.dirname(__filename), "..", "src", "profiles");


async function main() {
    const configPath = path.join(path.dirname(__filename), 'config.json');
    const config = getConfigSync(configPath);

    const prefixes = createPrefixes(config.profiles)

    const profiles: {namespace:string, source: string, profile: string}[] = config.profiles
    
    const generated: GeneratedProfile[] = [];
    for (const {source, profile} of profiles) {
        const quads = await fetchProfile(source)
        const cleanedQuads = cleanProfile(quads); // there are some issues with the TOSL. It's valid ttl, but the libraries struggle with it. It removes `skos:note`
        const ontology = await write(cleanedQuads, { prefixes })
        const result = persistProfile(profile, ontology);
        generated.push(result);
        console.log("Created the following profile:", result.constantName);    }

    writeProfileIndex(generated);
}
main()

// writes `src/profiles/index.ts`, re-exporting every profile constant
// plus a slug -> profile map so consumers can iterate over all profiles
function writeProfileIndex(profiles: GeneratedProfile[]): void {
    const lines = [
        "// Auto-generated by scripts/MakeProfiles.ts. Do not edit.",
        ...profiles.map(p => `import { ${p.constantName} } from "./${p.moduleName}";`),
        "",
        `export { ${profiles.map(p => p.constantName).join(", ")} };`,
        "",
        "export const PROFILES: Record<string, string> = {",
        ...profiles.map(p => `    ${JSON.stringify(p.slug)}: ${p.constantName},`),
        "};",
        "",
    ];
    fs.writeFileSync(path.join(profileDir, "index.ts"), lines.join("\n"));
}

interface GeneratedProfile {
    slug: string;
    constantName: string;
    moduleName: string; // file name without .ts
}

// persists the profile to 
// `src/profiles/source` as ttl
// `src/profiles/` as TS file
// returns a list of the TS constant created
function persistProfile(slug: string, profileSerialized: string): GeneratedProfile {
    const moduleName = `${toPascalCase(slug)}Profile`;       // dpv-odrl -> DpvOdrlProfile
    const constantName = `${toConstantCase(slug)}_PROFILE`;  // dpv-odrl -> DPV_ODRL_PROFILE
    // persist to typescript file and to 


    const profileTSContent = `export const ${constantName}: string = \`${profileSerialized}\``
    fs.writeFileSync(path.join(profileDir, `${moduleName}.ts`), profileTSContent);
    fs.writeFileSync(path.join(profileDir, "source", `${slug}.ttl`), profileSerialized);
    return { slug, constantName, moduleName };}

async function fetchProfile(url: string): Promise<Quad[]> {
    const { data } = await rdfDereferencer.dereference(url)
    const quads = await arrayifyStream(data) as Quad[]
    return quads;
}

function cleanProfile(quads: Quad[]): Quad[] {
    const store = new Store(quads);
    store.removeQuads(store.getQuads(null, namedNode("http://www.w3.org/2004/02/skos/core#note"), null, null))

    // this failed the parsing before:   skos:note "This RightOperand is intended to be used in conjunction with LeftOperands that specify actions or events impacting performance metrics. An example is \"causes eq degradation\", which expresses that the exertion of the action MUST not cause a service significant degradation" .

    return store.getQuads(null, null, null, null)
}

// generates prefixes based on the profiles in the config
// NOTE: we could automatically gather it from the profiles itself, but that requires a proper owl:ontology (which dpv-odrl currently does not have)
function createPrefixes(profiles: { profile: string, namespace: string }[]): Record<string, string> {
    const prefixes: Record<string, string> = {
        cr: "https://w3id.org/force/compliance-report#",
        dct: "http://purl.org/dc/terms/",
        ex: "http://example.org/",
        foaf: "http://xmlns.com/foaf/0.1/",
        odrl: "http://www.w3.org/ns/odrl/2/",
        schema: "https://schema.org/",
        xsd: "http://www.w3.org/2001/XMLSchema#",
        dpv: "https://w3id.org/dpv#",
        sotw: "https://w3id.org/force/sotw#",
        sh: "http://www.w3.org/ns/shacl#",
        rdfs: "http://www.w3.org/2000/01/rdf-schema#",
        owl: "http://www.w3.org/2002/07/owl#",
        skos: "http://www.w3.org/2004/02/skos/core#",
        tech: "https://w3id.org/dpv/tech#",
        pd: "https://w3id.org/dpv/pd#",
        vann: "http://purl.org/vocab/vann/",
        profile: "http://www.w3.org/ns/dx/prof/"
    }
    profiles.forEach(profile => { prefixes[profile.profile] = profile.namespace })
    return prefixes
}


function slugWords(slug: string): string[] {
    return slug
        .split(/[^a-zA-Z0-9]+/) // split on -, _, ., spaces, …
        .filter(Boolean)
        .map(w => w.toLowerCase());
}

function toPascalCase(slug: string): string {
    return slugWords(slug)
        .map(w => w[0].toUpperCase() + w.slice(1))
        .join("");
}
function toConstantCase(slug: string): string {
    return slugWords(slug).join("_").toUpperCase();
}